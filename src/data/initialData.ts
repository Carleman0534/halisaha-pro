// Helper to generate realistic evaluation profiles
const makeRatings = (base: number, highSkills: string[] = [], lowSkills: string[] = []) => {
  const result: Record<string, number> = {};
  CRITERIA_KEYS.forEach(c => {
    let score = base + Math.floor(Math.random() * 2) - (Math.random() > 0.5 ? 1 : 0);
    if (highSkills.includes(c.key)) score = Math.min(10, base + 2);
    if (lowSkills.includes(c.key)) score = Math.max(2, base - 3);
    result[c.key] = Math.max(1, Math.min(10, score));
  });
  return result;
};

